#!/usr/bin/env node
/**
 * node bin/build.mjs free|all [--no-zip]
 *
 * Produces dist/{slug}/ (and dist/{slug}.zip) for one edition (SPEC §2.2, §9.1):
 *  1. empty dist/{slug}
 *  2. filter the ledger by tier → inc/variants.php (plain PHP array, no runtime json_decode)
 *  3. css/base.css, css/editor.css, css/families/*.css (variant blocks cut by tier, minified)
 *  4. textures/ (whitelist: only files referenced by included variants)
 *  5. {slug}.php from src/plugin.php.tpl
 *  6. inc/ (src/php), build/ (wp-scripts output), languages/, readme.txt, uninstall.php (free only)
 *  7. zip
 *  8. verify the output; exit 1 on failure
 */
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import {
	ROOT,
	SRC,
	EDITIONS,
	UPDATE_HOST,
	loadLedger,
	filterLedger,
	readPackageVersion,
	splitFamilyCss,
	minifyCss,
	ensureDir,
	rmrf,
	copyDir,
	toPhp,
} from './lib.mjs';

const edition = process.argv[ 2 ];
const noZip = process.argv.includes( '--no-zip' );
if ( ! EDITIONS[ edition ] ) {
	console.error( 'Usage: node bin/build.mjs free|all [--no-zip]' );
	process.exit( 2 );
}
const cfg = EDITIONS[ edition ];
const version = readPackageVersion();
const DIST = path.join( ROOT, 'dist' );
const OUT = path.join( DIST, cfg.slug );

// 0. Ledger sanity first (same checks as CI).
execFileSync( process.execPath, [ path.join( ROOT, 'bin', 'check-variants.mjs' ) ], { stdio: 'inherit' } );

// 1. Clean.
rmrf( OUT );
if ( ! noZip ) {
	rmrf( path.join( DIST, `${ cfg.slug }.zip` ) );
}
ensureDir( OUT );

// 2. Ledger → inc/variants.php
const full = loadLedger();
const ledger = filterLedger( full, cfg.tiers );
ensureDir( path.join( OUT, 'inc' ) );
fs.writeFileSync(
	path.join( OUT, 'inc', 'variants.php' ),
	`<?php
/**
 * Generated by bin/build.mjs for the "${ edition }" edition. Do not edit.
 * Source of truth: src/variants.json
 *
 * @package HoloImageStyles
 */

defined( 'ABSPATH' ) || exit;

return ${ toPhp( { edition, version, families: ledger.families, variants: ledger.variants } ) };
`
);

// 3. CSS
ensureDir( path.join( OUT, 'css', 'families' ) );
for ( const file of [ 'base.css', 'editor.css', 'editor-ui.css' ] ) {
	const css = fs.readFileSync( path.join( SRC, 'css', file ), 'utf8' );
	fs.writeFileSync( path.join( OUT, 'css', file ), minifyCss( css ) + '\n' );
}
for ( const family of Object.keys( ledger.families ) ) {
	const file = path.join( SRC, 'css', 'families', `${ family }.css` );
	const { head, blocks } = splitFamilyCss( fs.readFileSync( file, 'utf8' ), `families/${ family }.css` );
	let css = head;
	for ( const [ name, body ] of blocks ) {
		if ( ledger.variants[ name ] ) {
			css += `\n${ body }\n`;
		}
	}
	fs.writeFileSync( path.join( OUT, 'css', 'families', `${ family }.css` ), minifyCss( css ) + '\n' );
}

// 4. Textures (whitelist).
const textures = new Set();
for ( const v of Object.values( ledger.variants ) ) {
	v.textures.forEach( ( t ) => textures.add( t ) );
}
ensureDir( path.join( OUT, 'textures' ) );
for ( const t of textures ) {
	fs.copyFileSync( path.join( SRC, 'textures', t ), path.join( OUT, 'textures', t ) );
}

// 4b. Editor thumbnails (whitelist, same rule as textures).
ensureDir( path.join( OUT, 'thumbs' ) );
for ( const key of Object.keys( ledger.variants ) ) {
	const thumb = path.join( SRC, 'thumbs', `${ key }.webp` );
	if ( fs.existsSync( thumb ) ) {
		fs.copyFileSync( thumb, path.join( OUT, 'thumbs', `${ key }.webp` ) );
	}
}

// 5. Main plugin file.
const tpl = fs.readFileSync( path.join( SRC, 'plugin.php.tpl' ), 'utf8' );
const activation =
	edition === 'all'
		? `
/*
 * Activating the All Effects edition deactivates the free edition (SPEC §7.2).
 * The free plugin files stay on disk; class-edition.php offers a "delete" button.
 */
register_activation_hook(
	__FILE__,
	static function () {
		require_once ABSPATH . 'wp-admin/includes/plugin.php';
		$free = 'holo-image-styles/holo-image-styles.php';
		if ( ! file_exists( WP_PLUGIN_DIR . '/' . $free ) ) {
			return;
		}
		if ( is_plugin_active_for_network( $free ) ) {
			deactivate_plugins( $free, true, true );
		} elseif ( is_plugin_active( $free ) ) {
			deactivate_plugins( $free, true, false );
		}
		set_site_transient( 'holo_offer_delete_free', 1, DAY_IN_SECONDS );
	}
);
`
		: '';
const main = tpl
	.replace( /\{\{NAME\}\}/g, cfg.name )
	.replace( /\{\{VERSION\}\}/g, version )
	.replace( /\{\{EDITION\}\}/g, edition )
	.replace( /\{\{EDITION_UPPER\}\}/g, edition.toUpperCase() )
	.replace( /\{\{PRIORITY\}\}/g, String( cfg.priority ) )
	.replace(
		/\{\{UPDATE_URI\}\}\n/g,
		edition === 'all' ? ` * Update URI:        https://${ UPDATE_HOST }/holo-image-styles/update.json\n` : ''
	)
	.replace( /\{\{ACTIVATION\}\}\n?/g, activation );
fs.writeFileSync( path.join( OUT, `${ cfg.slug }.php` ), main );

// 6. Copy the rest.
copyDir( path.join( SRC, 'php' ), path.join( OUT, 'inc' ) );
copyDir( path.join( ROOT, 'build' ), path.join( OUT, 'build' ) );
copyDir( path.join( ROOT, 'languages' ), path.join( OUT, 'languages' ) );
for ( const f of [ 'readme.txt', 'LICENSE' ] ) {
	if ( fs.existsSync( path.join( ROOT, f ) ) ) {
		fs.copyFileSync( path.join( ROOT, f ), path.join( OUT, f ) );
	}
}
if ( edition === 'free' ) {
	fs.copyFileSync( path.join( SRC, 'uninstall.php' ), path.join( OUT, 'uninstall.php' ) );
}
// Silence directory listing.
fs.writeFileSync( path.join( OUT, 'index.php' ), "<?php\n// Silence is golden.\n" );

// 7. Zip (folder name inside the zip = slug, as WordPress expects).
if ( ! noZip ) {
	execFileSync( 'zip', [ '-qr', '-X', `${ cfg.slug }.zip`, cfg.slug ], { cwd: DIST, stdio: 'inherit' } );
}

// 8. Verify.
const problems = [];
const mainSrc = fs.readFileSync( path.join( OUT, `${ cfg.slug }.php` ), 'utf8' );
if ( edition === 'free' && /Update URI/.test( mainSrc ) ) {
	problems.push( 'free edition must not have an Update URI header.' );
}
if ( edition === 'all' && ! /Update URI/.test( mainSrc ) ) {
	problems.push( 'all edition must have an Update URI header.' );
}
if ( /\{\{[A-Z_]+\}\}/.test( mainSrc ) ) {
	problems.push( 'unreplaced placeholder in main plugin file.' );
}
if ( edition === 'free' ) {
	const allOnly = Object.entries( full.variants ).filter( ( [ , v ] ) => v.tier === 'all' );
	const freeTextures = new Set();
	Object.values( ledger.variants ).forEach( ( v ) => v.textures.forEach( ( t ) => freeTextures.add( t ) ) );
	for ( const [ name, v ] of allOnly ) {
		const css = fs.readFileSync( path.join( OUT, 'css', 'families', `${ v.family }.css` ), 'utf8' );
		if ( css.includes( `data-holo-variant="${ name }"` ) ) {
			problems.push( `free edition CSS still contains variant "${ name }".` );
		}
		for ( const t of v.textures ) {
			if ( ! freeTextures.has( t ) && fs.existsSync( path.join( OUT, 'textures', t ) ) ) {
				problems.push( `free edition ships all-only texture "${ t }".` );
			}
		}
	}
	for ( const [ name ] of allOnly ) {
		if ( fs.existsSync( path.join( OUT, 'thumbs', `${ name }.webp` ) ) ) {
			problems.push( `free edition ships all-only thumbnail "${ name }".` );
		}
	}
	const variantsPhp = fs.readFileSync( path.join( OUT, 'inc', 'variants.php' ), 'utf8' );
	for ( const [ name ] of allOnly ) {
		if ( new RegExp( `'${ name }' =>` ).test( variantsPhp ) ) {
			problems.push( `free edition variants.php contains "${ name }".` );
		}
	}
	if ( ! fs.existsSync( path.join( OUT, 'uninstall.php' ) ) ) {
		problems.push( 'free edition must ship uninstall.php.' );
	}
} else if ( fs.existsSync( path.join( OUT, 'uninstall.php' ) ) ) {
	problems.push( 'all edition must not ship uninstall.php (option is shared with the free edition).' );
}
for ( const [ key, v ] of Object.entries( ledger.variants ) ) {
	if ( ! fs.existsSync( path.join( OUT, 'thumbs', `${ key }.webp` ) ) ) {
		problems.push( `thumbnail "${ key }.webp" missing from output (run "npm run thumbs").` );
	}
	for ( const t of v.textures ) {
		if ( ! fs.existsSync( path.join( OUT, 'textures', t ) ) ) {
			problems.push( `texture "${ t }" missing from output.` );
		}
	}
}
for ( const f of [ 'build/view.js', 'build/editor.js', 'inc/class-plugin.php', 'inc/class-render.php', 'inc/class-variants.php', 'inc/class-editor.php', 'inc/class-edition.php', 'css/base.css', 'css/editor.css', 'css/editor-ui.css' ] ) {
	if ( ! fs.existsSync( path.join( OUT, f ) ) ) {
		problems.push( `required file missing: ${ f } (run "npm run build" first?)` );
	}
}
if ( problems.length ) {
	console.error( `build ${ edition }: verification failed` );
	problems.forEach( ( p ) => console.error( '  - ' + p ) );
	process.exit( 1 );
}

const size = ( p ) => ( fs.existsSync( p ) ? ( fs.statSync( p ).size / 1024 ).toFixed( 1 ) + ' KB' : 'n/a' );
console.log(
	`build ${ edition }: OK → dist/${ cfg.slug } (${ Object.keys( ledger.variants ).length } variants, ${ textures.size } textures, zip ${ size( path.join( DIST, `${ cfg.slug }.zip` ) ) })`
);
